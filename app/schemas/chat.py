from typing import Annotated

from pydantic import BaseModel, ConfigDict, Field, StringConstraints

MAX_MESSAGE_LENGTH = 4000

ChatMessage = Annotated[
    str,
    StringConstraints(strip_whitespace=True, min_length=1, max_length=MAX_MESSAGE_LENGTH),
]


class ChatRequest(BaseModel):
    model_config = ConfigDict(extra="forbid")

    message: ChatMessage = Field(
        description=(
            "The user's message. Leading and trailing whitespace is removed; "
            f"the result must be between 1 and {MAX_MESSAGE_LENGTH} characters."
        ),
        examples=["What is our vacation policy?"],
    )


class TokenUsage(BaseModel):
    input_tokens: int = Field(description="Tokens in the prompt, including instructions.")
    output_tokens: int = Field(description="Tokens generated by the model.")
    total_tokens: int = Field(description="Sum of input and output tokens.")


class ChatResponse(BaseModel):
    reply: str = Field(
        description="The assistant's reply.",
        examples=["Mock response to: What is our vacation policy?"],
    )
    model: str = Field(
        description="Configured identifier of the model that produced the reply.",
        examples=["mock-llm"],
    )
    usage: TokenUsage | None = Field(
        default=None,
        description="Token usage reported by the provider; null when not available.",
    )


class ErrorResponse(BaseModel):
    detail: str = Field(
        description="Safe, human-readable error message.",
        examples=["LLM provider timed out"],
    )
